// Identifier case styles with examples:

// camelCase: first word lowercase, subsequent words capitalized
let myVariableName = "camelCase";
let userAge = 30;

// PascalCase: every word capitalized
let UserProfile = {};
let InvoiceTotal = 100;

// snake_case: words separated by underscores
let user_name = "snake_case";
let max_value = 50;

// UPPER_SNAKE_CASE: constants often use uppercase and underscores
let MAX_LIMIT = 100;
let API_KEY = "abcd1234";

//Hungarian Notation: prefix indicates type or purpose (less common in modern JavaScript)
let strName = "John"; // str prefix indicates a string 
let bActive = true; // b prefix indicates a boolean
let nCount = 5; // n prefix indicates a number
let arrItems = [1, 2, 3]; // arr prefix indicates an array

